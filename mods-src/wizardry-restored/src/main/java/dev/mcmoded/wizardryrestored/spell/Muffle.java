/// Приглушение: 30 секунд существа дальше 6 блоков не замечают заклинателя, шаги беззвучны.
public class Muffle extends Spell {
    @Override
    public boolean cast(PlayerCastContext ctx) {
        if (ctx.world() instanceof ServerLevel server) {
            int duration = (int) (property(DefaultProperties.DURATION) * ctx.modifiers().get(SpellModifiers.DURATION));
            SpellStates.data(ctx.caster()).putLong(SpellStates.MUFFLE_UNTIL, server.getGameTime() + duration);
            server.sendParticles(ParticleTypes.SMOKE, ctx.caster().getX(), ctx.caster().getY() + 1, ctx.caster().getZ(), 20, 0.3, 0.5, 0.3, 0.01);
        }
        this.playSound(ctx.world(), ctx.caster(), ctx.castingTicks(), -1);
        return true;
    }

    @Override
    protected SpellProperties properties() {
        return SpellProperties.builder()
                .assignBaseProperties(SpellTiers.NOVICE, Elements.SORCERY, SpellTypes.BUFF, SpellAction.POINT_UP, 5, 0, 25)
                .add(DefaultProperties.DURATION, 600)
                .build();
    }
}
